let lang = 'ar';
document.querySelectorAll('[data-i]').forEach(el => {
  const key = el.dataset.i;
  if (copy.ar[key]) el.textContent = copy.ar[key];
});

document.getElementById('langToggle').addEventListener('click', () => {
  lang = lang === 'ar' ? 'en' : 'ar';
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';

  document.querySelectorAll('[data-i]').forEach(el => {
    const key = el.dataset.i;
    if (copy[lang][key]) el.textContent = copy[lang][key];
  });

  document.getElementById('langToggle').textContent = lang === 'ar' ? 'EN ↗' : 'عربي ↗';
  document.querySelector('meta[name="description"]').content = copy[lang].description;
  document.title = lang === 'ar' ? 'ملفي | مطور برمجيات' : 'Portfolio | Software Developer';
  document.querySelector('nav').setAttribute('aria-label', lang === 'ar' ? 'التنقل' : 'Navigation');
});